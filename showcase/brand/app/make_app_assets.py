#!/usr/bin/env python3
"""Generate the mobile-app brand assets from the CSS tokens (single source: ../brand.css + ../brand-status.css):
  tokens.json, theme.ts, tsconfig.json, assets/*.svg and assets/*.png (icon, adaptive foreground, splash light/dark, favicon).
Run: NW_FONT_DIR=<node_modules>/@fontsource python3 -I make_app_assets.py     (Chromium via Node playwright renders the PNGs)
Icons use the existing logo mark geometry (nilwerk.de / ../logo/nilwerk-mark.svg), nothing new is drawn.
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import build_post as v01  # noqa: E402  (render helpers only)

BASE = (HERE.parent / "brand.css").read_text()
STAT = (HERE.parent / "brand-status.css").read_text()


def block(css, start):
    i = css.index(start)
    return css[css.index("{", i) + 1: css.index("}", i)]


def parse(t):
    return dict(re.findall(r"--nw-([a-z-]+):\s*(#[0-9a-fA-F]{6})", t))


def camel(k):
    p = k.split("-")
    return p[0] + "".join(x.capitalize() for x in p[1:])


light = {**parse(block(BASE, ":root {")), **parse(block(STAT, ":root {"))}
dark = {**light, **parse(block(BASE, ':root[data-theme="dark"]')), **parse(block(STAT, ':root[data-theme="dark"]'))}
KEEP = ["bg", "surface", "ink", "muted", "line", "rule", "accent", "accent-ink", "accent-soft", "warn", "ok", "ok-soft", "dry", "dry-soft", "wet", "wet-soft",
        "low", "low-soft", "offline", "offline-soft", "danger", "danger-soft", "danger-ink", "control"]
colors = {name: {camel(k): tk[k] for k in KEEP if k in tk} for name, tk in (("light", light), ("dark", dark))}

tokens = {
    "_note": "Generated by make_app_assets.py from showcase/brand/brand.css + brand-status.css (v0.1 brand, proposal). Do not edit by hand.",
    "color": colors,
    "spacing": {"xs": 4, "sm": 8, "md": 12, "lg": 16, "xl": 24, "xxl": 32, "xxxl": 48},
    "radius": {"sm": 6, "md": 10, "lg": 14, "pill": 999},
    "fontFamily": {"display": "SpaceGrotesk_700Bold", "displayMedium": "SpaceGrotesk_500Medium", "body": "Inter_400Regular",
                   "bodyStrong": "Inter_600SemiBold", "mono": "JetBrainsMono_400Regular", "monoStrong": "JetBrainsMono_600SemiBold"},
    "typography": {
        "display": {"font": "display", "size": 34, "lineHeight": 40, "letterSpacing": -0.7},
        "h1": {"font": "display", "size": 28, "lineHeight": 34, "letterSpacing": -0.5},
        "h2": {"font": "display", "size": 22, "lineHeight": 28, "letterSpacing": -0.3},
        "h3": {"font": "display", "size": 18, "lineHeight": 24, "letterSpacing": -0.2},
        "body": {"font": "body", "size": 16, "lineHeight": 24, "letterSpacing": 0},
        "bodyStrong": {"font": "bodyStrong", "size": 16, "lineHeight": 24, "letterSpacing": 0},
        "caption": {"font": "body", "size": 13, "lineHeight": 18, "letterSpacing": 0},
        "label": {"font": "monoStrong", "size": 13, "lineHeight": 18, "letterSpacing": 1},
        "number": {"font": "monoStrong", "size": 40, "lineHeight": 44, "letterSpacing": -1.5},
    },
    "status": {
        "ok": {"color": "ok", "soft": "okSoft", "labelKey": "status.ok", "shape": "circle"},
        "dry": {"color": "dry", "soft": "drySoft", "labelKey": "status.dry", "shape": "triangle"},
        "wet": {"color": "wet", "soft": "wetSoft", "labelKey": "status.wet", "shape": "diamond"},
        "lowBattery": {"color": "low", "soft": "lowSoft", "labelKey": "status.lowBattery", "shape": "square"},
        "offline": {"color": "offline", "soft": "offlineSoft", "labelKey": "status.offline", "shape": "ring"},
        "error": {"color": "danger", "soft": "dangerSoft", "labelKey": "status.error", "shape": "cross"},
    },
    "minTouchTarget": 48,
}
(HERE / "tokens.json").write_text(json.dumps(tokens, indent=2) + "\n")


def ts_obj(o, ind=0):
    pad = "  " * ind
    if isinstance(o, dict):
        inner = ",\n".join(f"{pad}  {k}: {ts_obj(v, ind + 1)}" for k, v in o.items())
        return "{\n" + inner + f"\n{pad}}}"
    if isinstance(o, str):
        return json.dumps(o)
    return json.dumps(o)


theme_ts = f"""/**
 * Nilwerk app theme (v0.1 brand, proposal). GENERATED by make_app_assets.py from tokens.json: do not edit by hand.
 * Pure TypeScript, no React Native import, so it type-checks standalone. Use with React Native / Expo:
 *
 *   import {{ useColorScheme, Text }} from 'react-native';
 *   import {{ getTheme, statusStyle }} from './theme';
 *   const t = getTheme(useColorScheme());
 *   <Text style={{{{ color: t.color.ink, ...t.type.body }}}}>Hello</Text>
 *
 * Fonts (install once): npx expo install @expo-google-fonts/space-grotesk @expo-google-fonts/inter @expo-google-fonts/jetbrains-mono expo-font
 * and load SpaceGrotesk_500Medium, SpaceGrotesk_700Bold, Inter_400Regular, Inter_600SemiBold, JetBrainsMono_400Regular, JetBrainsMono_600SemiBold.
 * Status is never colour alone: always show the label (strings come from app/strings/en.json, key = labelKey) and the shape.
 */

export type Scheme = 'light' | 'dark';
export type PlantStatus = 'ok' | 'dry' | 'wet' | 'lowBattery' | 'offline' | 'error';

export const colors = {ts_obj(colors)} as const;

export const spacing = {ts_obj(tokens["spacing"])} as const;
export const radius = {ts_obj(tokens["radius"])} as const;
export const fontFamily = {ts_obj(tokens["fontFamily"])} as const;
export const minTouchTarget = {tokens["minTouchTarget"]};

export interface TextStyleToken {{
  fontFamily: string;
  fontSize: number;
  lineHeight: number;
  letterSpacing: number;
}}

const typo = (font: keyof typeof fontFamily, size: number, lineHeight: number, letterSpacing: number): TextStyleToken => ({{
  fontFamily: fontFamily[font],
  fontSize: size,
  lineHeight,
  letterSpacing,
}});

export const type = {{
  display: typo('display', 34, 40, -0.7),
  h1: typo('display', 28, 34, -0.5),
  h2: typo('display', 22, 28, -0.3),
  h3: typo('display', 18, 24, -0.2),
  body: typo('body', 16, 24, 0),
  bodyStrong: typo('bodyStrong', 16, 24, 0),
  caption: typo('body', 13, 18, 0),
  label: typo('monoStrong', 13, 18, 1),
  number: typo('monoStrong', 40, 44, -1.5),
}} as const;

// FR-A07 (push alerts): too dry, too wet, low battery, device offline map to these statuses. Thresholds and clear rules are NOT
// repeated here: see projects/plant-monitor/docs/requirements-v1.0-delta.md, row FR-A07 (single source). The four edge-AI alert
// kinds (wetting_unexpected, waterlogged, sensor_out_of_soil, sensor_fault) are an open decision for the app owners: see app/README.md.
export const statusMeta: Record<PlantStatus, {{ colorKey: keyof typeof colors.light; softKey: keyof typeof colors.light; labelKey: string; shape: string }}> = {{
  ok: {{ colorKey: 'ok', softKey: 'okSoft', labelKey: 'status.ok', shape: 'circle' }},
  dry: {{ colorKey: 'dry', softKey: 'drySoft', labelKey: 'status.dry', shape: 'triangle' }},
  wet: {{ colorKey: 'wet', softKey: 'wetSoft', labelKey: 'status.wet', shape: 'diamond' }},
  lowBattery: {{ colorKey: 'low', softKey: 'lowSoft', labelKey: 'status.lowBattery', shape: 'square' }},
  offline: {{ colorKey: 'offline', softKey: 'offlineSoft', labelKey: 'status.offline', shape: 'ring' }},
  error: {{ colorKey: 'danger', softKey: 'dangerSoft', labelKey: 'status.error', shape: 'cross' }},
}};

export function getTheme(scheme?: string | null) {{
  const name: Scheme = scheme === 'dark' ? 'dark' : 'light';
  return {{ name, color: colors[name], spacing, radius, type, fontFamily, minTouchTarget }};
}}

/** Colours, label key and shape for a plant status badge, for the given scheme. */
export function statusStyle(status: PlantStatus, scheme?: string | null) {{
  const name: Scheme = scheme === 'dark' ? 'dark' : 'light';
  const m = statusMeta[status];
  return {{ color: colors[name][m.colorKey], background: colors[name][m.softKey], labelKey: m.labelKey, shape: m.shape }};
}}
"""
(HERE / "theme.ts").write_text(theme_ts)
(HERE / "tsconfig.json").write_text(json.dumps({"compilerOptions": {"target": "ES2019", "module": "ESNext", "moduleResolution": "bundler", "strict": True,
                                                                     "noEmit": True, "skipLibCheck": True}, "files": ["theme.ts"]}, indent=2) + "\n")

# ---- icon assets (SVG sources + PNG) from the existing mark ----
MARK_INNER = ('<path d="M10 22V9.5l12 12.5V9.5" fill="none" stroke="#3fc79a" stroke-width="2.8" stroke-linecap="round" stroke-linejoin="round"/>'
              '<circle cx="10" cy="22" r="2.6" fill="#15181d" stroke="#3fc79a" stroke-width="1.8"/>'
              '<circle cx="22" cy="9.5" r="2.6" fill="#15181d" stroke="#3fc79a" stroke-width="1.8"/>'
              '<path d="M6.5 26.6c2.4-1.5 4.8-1.5 7.2 0s4.8 1.5 7.2 0 4.8-1.5 6.9-.1" fill="none" stroke="#8fd9ff" stroke-opacity=".7" stroke-width="1.4" stroke-linecap="round"/>')
PLATE = '<rect x="1" y="1" width="30" height="30" rx="9" fill="#15181d" stroke="#ffffff" stroke-opacity=".12"/>'
FD = "font-family=\"'Space Grotesk', Inter, sans-serif\" font-weight=\"700\""
assets = HERE / "assets"
assets.mkdir(exist_ok=True)


def svg(w, h, body):
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">{body}</svg>\n'


def mark_at(cx, cy, size, plate=True):
    s = size / 32
    return f'<g transform="translate({cx - size / 2:.1f} {cy - size / 2:.1f}) scale({s:.4f})">{PLATE if plate else ""}{MARK_INNER}</g>'


files = {
    # iOS/Expo icon: opaque, full-bleed ink, mark (without its own plate) at about 60 % so the OS corner mask never cuts it
    "icon-1024.svg": svg(1024, 1024, '<rect width="1024" height="1024" fill="#15181d"/>' + mark_at(512, 512, 620, plate=False)),
    # Android adaptive foreground: RGBA PNG with real transparency (rendered with omitBackground), mark inside the 66 % safe zone (676 px); background colour #15181d is set in app.json
    "adaptive-icon-foreground-1024.svg": svg(1024, 1024, mark_at(512, 512, 520, plate=False)),
    "favicon-48.svg": svg(48, 48, '<rect width="48" height="48" rx="12" fill="#15181d"/>' + mark_at(24, 24, 36, plate=False)),
}
for theme, bg, ink, acc in (("light", "#f6f4ef", "#15181d", "#0f7a5c"), ("dark", "#101317", "#ecebe7", "#3fc79a")):
    files[f"splash-{theme}-1284x2778.svg"] = svg(1284, 2778, f'<rect width="1284" height="2778" fill="{bg}"/>' + mark_at(642, 1250, 300) +
        f'<text x="642" y="1530" text-anchor="middle" {FD} font-size="96" letter-spacing="-3" fill="{ink}">nil<tspan fill="{acc}">werk</tspan></text>')
jobs = []
for n, s in files.items():
    (assets / n).write_text(s)
    if n.startswith("adaptive"):
        continue  # rendered separately with a transparent background
    jobs.append((assets / n, assets / n.replace(".svg", ".png")))
v01.render_png(jobs, scale=1)
import os, subprocess  # noqa: E402
env = dict(os.environ)
env.setdefault("NODE_PATH", "/opt/node-tools/node_modules")
subprocess.run(["node", str(HERE.parent / "render_transparent.js"), str(assets / "adaptive-icon-foreground-1024.svg"),
                str(assets / "adaptive-icon-foreground-1024.png")], check=True, env=env)
print("app assets written")
