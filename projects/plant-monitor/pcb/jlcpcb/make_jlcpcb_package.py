def parse_sexp(text):
    tok = re.findall(r'\(|\)|"(?:[^"\\]|\\.)*"|[^\s()]+', text)
    root, stack = [], [[]]
    root = stack[0]
    for t in tok:
        if t == "(":
            node = []
            stack[-1].append(node)
            stack.append(node)
        elif t == ")":
            stack.pop()
        elif t.startswith('"'):
            stack[-1].append(t[1:-1])
        else:
            stack[-1].append(t)
    return root


def kids(node, name):
    return [c for c in node if isinstance(c, list) and c and c[0] == name]


def kid(node, name):
    k = kids(node, name)
    return k[0] if k else None


def rot(x, y, deg):
    a = math.radians(deg)
    return x * math.cos(a) - y * math.sin(a), x * math.sin(a) + y * math.cos(a)


def at_of(node):
    a = kid(node, "at")
    return float(a[1]), float(a[2]), (float(a[3]) if len(a) > 3 else 0.0)


def load_board(path):
    pcb = parse_sexp(open(path, encoding="utf8").read())[0]
    fps = {}
    for f in kids(pcb, "footprint"):
        ref, silk_text = None, 0
        for p in kids(f, "property"):
            if len(p) >= 3 and p[1] == "Reference":
                ref = p[2]
        fx, fy, fr = at_of(f)
        pads = []
        for p in kids(f, "pad"):
            px, py, pr = at_of(p)
            sz = kid(p, "size")
            w, h = float(sz[1]), float(sz[2])
            # KiCad board file: the pad angle is the ABSOLUTE orientation (footprint rotation included). Slice 1 added the two
            # angles here, which double-rotates; the real J1/J2 footprints in CI DRC (clean) confirm the absolute reading.
            if abs((pr % 180) - 90) < 1e-6:
                w, h = h, w
            ax, ay = rot(px, py, fr)
            dr = kid(p, "drill")
            pads.append(dict(num=p[1], type=p[2], x=fx + ax, y=fy + ay, w=w, h=h, drill=("slot" if dr and "oval" in dr else "round" if dr else None)))
        fps[ref] = dict(lib=f[1], x=fx, y=fy, r=fr, pads=pads, ref=ref, lib_ok=True)
    vias = []
    for v in kids(pcb, "via"):
        x, y, _ = at_of(v)
        vias.append((x, y, float(kid(v, "size")[1]), float(kid(v, "drill")[1])))
    edge = []
    for g in pcb:
        if isinstance(g, list) and g and str(g[0]).startswith("gr_"):
            lay = kid(g, "layer")
            if lay and lay[1] == "Edge.Cuts":
                for key in ("start", "end", "mid"):
                    k = kid(g, key)
                    if k:
                        edge.append((float(k[1]), float(k[2])))
    tracks = sum(1 for g in pcb if isinstance(g, list) and g and g[0] in ("segment", "arc"))
    zones = [z for z in kids(pcb, "zone")]
    filled = sum(1 for z in zones if kid(z, "filled_polygon"))
    thickness = float(kid(kid(pcb, "general"), "thickness")[1])
    layers = [l for l in kid(pcb, "layers")[1:] if isinstance(l, list) and len(l) > 2 and l[2] == "signal"]
    return dict(fps=fps, vias=vias, edge=edge, tracks=tracks, zones=len(zones), zones_filled=filled,
                thickness=thickness, cu_layers=len(layers))


def vias_in_smd_pads(vias, fps):
    hits = []
    for i, (vx, vy, _, _) in enumerate(vias):
        for ref, f in fps.items():
            for p in f["pads"]:
                if p["type"] != "smd":
                    continue
                if abs(vx - p["x"]) <= p["w"] / 2 and abs(vy - p["y"]) <= p["h"] / 2:
                    hits.append((i, ref, p["num"]))
    return hits


