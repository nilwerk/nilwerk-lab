def read_bom_pcb():
    rows = list(csv.DictReader(open(BOM_PCB, encoding="utf8")))
    out = []
    for r in rows:
        refs = [x.strip() for x in r["Designator"].split(",") if x.strip()]
        out.append(dict(refs=refs, qty=int(r["Qty"]), value=r["Value"], footprint=r["Footprint"],
                        lcsc=r["LCSC"].strip(), mpn=r["MPN"], note=r["Note"]))
    return out


def read_draft():
    d = {}
    for r in csv.DictReader(open(BOM_DRAFT, encoding="utf8")):
        if r["lcsc_pn"]:
            d.setdefault(r["lcsc_pn"], r)
    return d, {r["ref"]: r for r in csv.DictReader(open(BOM_DRAFT, encoding="utf8"))}


def parse_breaks(s):
    out = []
    for item in (s or "").split():
        q, p = item.split(":")
        out.append((int(q), float(p)))
    return sorted(out)


def unit_price(breaks, qty):
    if not breaks:
        return None, "no price"
    best = None
    for q, p in breaks:
        if q <= qty:
            best = p
    if best is None:
        return breaks[0][1], "below first price break, first break used (UNVERIFIED for this quantity)"
    return best, "ok"


def run_check(cmd_args):
    """Run a repo check script with /usr/bin/python3 -I in the pcb dir and return (rc, last lines)."""
    r = subprocess.run(["/usr/bin/python3", "-I"] + cmd_args, cwd=PCB, capture_output=True, text=True)
    lines = (r.stdout + r.stderr).strip().splitlines()
    return r.returncode, lines


def fab_checks(fab):
    res = {}
    gdir = os.path.join(fab, "gerbers")
    names = os.listdir(gdir)
    need = {"F.Cu": r"-F_Cu\.gtl", "B.Cu": r"-B_Cu\.gbl", "F.Mask": r"-F_Mask\.gts", "B.Mask": r"-B_Mask\.gbs",
            "F.SilkS": r"-F_Silkscreen\.gto", "B.SilkS": r"-B_Silkscreen\.gbo", "F.Paste": r"-F_Paste\.gtp",
            "B.Paste": r"-B_Paste\.gbp", "Edge.Cuts": r"-Edge_Cuts\.gm1", "PTH drill": r"\.drl$"}
    res["gerber_missing"] = [k for k, pat in need.items() if not any(re.search(pat, n) for n in names)]
    drl = open(os.path.join(gdir, "plant-monitor.drl"), encoding="utf8").read()
    res["drill_tools"] = sorted(set(re.findall(r"^T\d+C([\d.]+)", drl, re.M)), key=float)
    res["drill_holes"] = len(re.findall(r"^X-?[\d.]+Y-?[\d.]+$", drl, re.M))
    res["drill_slots"] = len(re.findall(r"G85", drl))
    res["drill_files"] = sorted(n for n in names if n.endswith(".drl"))
    res["gerber_files"] = len(names)
    drc = open(os.path.join(fab, "drc.rpt"), encoding="utf8").read()
    erc = open(os.path.join(fab, "erc.rpt"), encoding="utf8").read()
    m = re.search(r"Found (\d+) DRC violations", drc)
    res["drc"] = int(m.group(1)) if m else None
    m = re.search(r"Found (\d+) unconnected pads", drc)
    res["drc_unconnected_pads"] = int(m.group(1)) if m else None
    m = re.search(r"ERC messages:\s*(\d+)\s+Errors\s+(\d+)\s+Warnings\s+(\d+)", erc)
    res["erc"] = tuple(int(x) for x in m.groups()) if m else None
    return res, names


def zip_gerbers(fab, out_zip):
    gdir = os.path.join(fab, "gerbers")
    with zipfile.ZipFile(out_zip, "w", zipfile.ZIP_DEFLATED) as z:
        for n in sorted(os.listdir(gdir)):
            info = zipfile.ZipInfo(n, date_time=(2026, 11, 9, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            with open(os.path.join(gdir, n), "rb") as fh:
                z.writestr(info, fh.read())


