    edge = board["edge"]
    bw = max(p[0] for p in edge) - min(p[0] for p in edge)
    bh = max(p[1] for p in edge) - min(p[1] for p in edge)
    via_pad_hits = vias_in_smd_pads(board["vias"], fps)
    n_pad_round = sum(1 for f in fps.values() for p in f["pads"] if p["drill"] == "round")
    n_pad_slot = sum(1 for f in fps.values() for p in f["pads"] if p["drill"] == "slot")
    via_drill = sorted({round(v[3], 3) for v in board["vias"]})
    via_pad = sorted({round(v[2], 3) for v in board["vias"]})
    fiducials = [r for r, f in fps.items() if "fiducial" in f["lib"].lower()]
    tooling = [r for r, f in fps.items() if "tooling" in f["lib"].lower() or "mountinghole" in f["lib"].lower()]
    # slice 2: U1, J1, J2, SW1-SW3 and the standard parts use library / drawing pads (footprints/SOURCES.md); these remain
    placeholders = sorted({"U5 AHT20 DFN-6", "U6 BH1750 WSOF-6", "E1 soil probe copper (own copper, no LCSC, not in CPL; size depends on Q5)"})

    def chk(label):
        for ln in lay_lines:
            if label in ln:
                return "PASS" if ln.startswith("PASS") else "FAIL"
        return "NOT FOUND"

    def chk_line(label):
        for ln in lay_lines:
            if label in ln:
                return ln.strip()
        return "check_layout line not found: " + label

    via_ring = (min(via_pad) - max(via_drill)) / 2 if via_pad and via_drill else None
    layers_ok = board["cu_layers"] == 2
    cu_fill_status = f"{board['zones_filled']}/{board['zones']} zones filled"

    # ---- dry-run checklist rows ----
    R = []  # (id, item, jlc_limit, this_board, result, note)
    def row(i, item, lim, val, res, note=""):
        R.append((i, item, lim, val, res, note))

    row("F1", "Copper layers", "1-32 layers; 2-layer FR-4 standard", f"{board['cu_layers']} layers", "PASS" if layers_ok else "FAIL", JLC_SRC)
    row("F2", "Board thickness", "FR-4 0.4-4.5 mm; 1.6 mm in list (+-10 %)", f"{board['thickness']} mm", "PASS" if board['thickness'] == 1.6 else "FAIL", JLC_SRC)
    row("F3", "Outer copper weight", "2-layer: 1 / 2 / 2.5 / 3.5 / 4.5 oz", "1 oz (not stored in the board file; choice in cart)", "CHOICE", JLC_SRC)
    row("F4", "Board size", "min 5 x 5 mm; 2-layer FR-4 max 1020 x 600 mm", f"{bw:.2f} x {bh:.2f} mm, 1 board", "PASS", JLC_SRC)
    # Panel (Nora / Arsany round, 2026-11-10): 2 boards, rails, tooling holes, fiducials, outline unchanged. panel.py checks the geometry;
    # the panel Gerber/drill set does not exist yet, so the Gerber-level rows stay FAIL/OPEN.
    sys.path.insert(0, HERE)
    import panel as PNL
    pl = PNL.layout()
    pchk = PNL.checks(pl)
    pgeo = f"2 boards {bw:.2f} x {bh:.2f} mm in a {pl['W']:.1f} x {pl['H']:.1f} mm panel (rails {PNL.RAIL:.0f} mm, board gap {PNL.BOARD_GAP:.0f} mm)"
