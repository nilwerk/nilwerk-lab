"""Task 4.AI2 end to end: Mendeley real data -> Model B wetting (float + int8 TFLite) + Model A baseline -> report.

Usage: python -I scripts/train_all.py <raw_dir> <out_dir>      (raw_dir = output of scripts/fetch_mendeley.sh)
Writes <out_dir>/model-b-wetting-v0.json, model_b_wetting_int8.tflite, size_report.json. Real data only (no synthetic
faults). TEST is evaluated once per seed after p_fast is fixed on VAL. FR-E01, FR-E02, FR-E03, FR-E04, A-019, A-032.
"""
