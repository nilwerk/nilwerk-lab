def git_sha() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return "unknown"


def evaluate(p_by_split: dict, win: dict, thr: float) -> dict:
    out = {}
    vu = T.usable(win["val"])       # rule threshold at the same FP budget, chosen on VAL only (concept 2.3 baseline row)
    rule_k, _ = T.choose_p_fast(T.rule_score(win["val"]["X"][vu]).astype(float), win["val"]["y"][vu], start=float(T.RULE_RISE_PTS))
    for s in ("val", "test"):
        u = T.usable(win[s])
        y = win[s]["y"][u]
        model_pred = p_by_split[s][u] >= thr
        rule_pred = T.rule_predict(win[s]["X"][u])
        rule_eq = T.rule_predict(win[s]["X"][u], rule_k)
        out[s] = {"n_positive": int((y == 1).sum()), "n_negative": int((y == 0).sum()),
                  "n_ignored_dropped": int((~u).sum()),
                  "model": T.per_class_metrics(y, model_pred), "rule_baseline": T.per_class_metrics(y, rule_pred),
                  "rule_equal_fp_budget": {"rise_pts": rule_k, **T.per_class_metrics(y, rule_eq)},
                  "unexplained_wetting_model": T.unexplained_report(win[s], p_by_split[s] >= thr),
                  "unexplained_wetting_rule": T.unexplained_report(win[s], T.rule_predict(win[s]["X"]))}
    return out


def fmt(v, pct=True):
    return "n/a" if v is None else (f"{100 * v:.1f} %" if pct else f"{v:.2f}")


def row(name, split, m, n_pos, n_neg):
    w, n = m["wetting"], m["normal"]
    ci = w["recall_ci95"]
    return (f"| {name} | {split} | {n_pos}/{n_neg} | {w['tp']}/{w['fp']}/{w['fn']} | {fmt(w['precision'])} | {fmt(w['recall'])} "
            f"({fmt(ci[0]) if ci else 'n/a'} to {fmt(ci[1]) if ci else 'n/a'}) | {fmt(n['precision'])} | {fmt(n['recall'])} | "
            f"{fmt(m['false_alerts_per_unit_week'], False)} |")


def sweep_md(path: Path) -> list:
    """Rule threshold sweep table (scripts/rule_sweep.py, review C1); empty if the sweep file is absent."""
    if not path.exists():
        return []
    sw = json.loads(path.read_text())
    L_ = ["", "## Rule baseline swept over its threshold (review C1; `scripts/rule_sweep.py`)", "",
          "The rule has a single parameter (rise in points over 1 h, scale 0-100). Every threshold is listed, none is picked. "
          "Wetting recall (Wilson 95 % interval) and false alerts per unit-week (FA/wk), same windows and ignore mask as above.", "",
          "| Rule threshold (pts/h) | VAL recall | VAL FA/wk | TEST recall | TEST FA/wk |", "|---|---|---|---|---|"]
    for a, b in zip(sw["val"], sw["test"]):
        def c(x):
            lo, hi = x["recall_ci95"]
            return f"{100 * x['recall']:.0f} % ({100 * lo:.0f}-{100 * hi:.0f}) [{x['tp']}/{x['n_pos']}]"
        L_.append(f"| >= {a['rise_pts']} | {c(a)} | {a['fa_per_unit_week']:.2f} | {c(b)} | {b['fa_per_unit_week']:.2f} |")
    L_ += ["", "Reading: on TEST the rule finds 0 of 20 at every threshold that gives <= 1 FA/unit-week (>= 60 pts/h or higher; at 50 pts/h it is 1.56 FA/wk, still 0 of 20). "
           "Its recall rises only as the threshold falls: 30 % at 9 FA/wk, 60 % at 15 FA/wk, 80 % at 25 FA/wk. "
           "So the equal-false-alert-rate rule baseline is a degenerate threshold (it fires only on near-saturating jumps), and 'MLP vs 0 %' is a weak comparison. "
           "The fair statement is the whole curve: at <= 1 FA/unit-week the int8 MLP finds 40 % (8/20, 0.52 FA/wk) and the rule 0 %; "
           "at about 9 FA/wk the rule finds 30 %; at 25 FA/wk it finds 80 %. Neither reaches the 95 % target at <= 1 FA/wk."]
    return L_


