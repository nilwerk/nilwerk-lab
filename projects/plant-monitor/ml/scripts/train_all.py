def main(raw_dir: str, out_dir: str) -> None:
    out = Path(out_dir); out.mkdir(parents=True, exist_ok=True)
    raw, _ = loaders.load_mendeley(Path(raw_dir))
    sp = prep.preprocess(raw, inject=False, seed=0)          # real data only
    sp.pop("_calibration")
    ds = export.build_dataset(sp)
    win = {s: T.build_wetting_windows(ds[s]) for s in ("train", "val", "test")}
    tr_u = T.usable(win["train"])
    Xtr, ytr = win["train"]["X"][tr_u], win["train"]["y"][tr_u]
    report = {"task": "4.AI2", "git_sha": git_sha(), "data": "mendeley v2 doi 10.17632/c837v6p8ph.2, real rows only, inject=False",
              "requirements": ["FR-E01", "FR-E02", "FR-E03", "FR-E04", "NFR-01", "NFR-02"],
              "counts": {s: {"windows": int(len(win[s]["y"])), "pos": int((win[s]["y"] == 1).sum()), "neg": int((win[s]["y"] == 0).sum()),
                             "ignore": int((win[s]["y"] == -1).sum())} for s in win},
              "seeds": list(T.SEEDS), "reported_seed": T.SEEDS[0], "fp_budget_per_tick": T.FP_BUDGET_PER_TICK, "float": {}, "int8": {}}
    first = None
    for seed in T.SEEDS:
        model = T.train_model(Xtr, ytr, seed)
        pv = {s: T.predict_p1(model, win[s]["X"]) for s in ("val", "test")}
        vu = T.usable(win["val"])
        thr, met = T.choose_p_fast(pv["val"][vu], win["val"]["y"][vu])
        res = evaluate(pv, win, thr)
        res.update({"p_fast": thr, "fp_budget_met_on_val": met})
        report["float"][f"seed{seed}"] = res
        if seed == T.SEEDS[0]:
            first = (model, thr, pv)
    model, thr, pv = first
    tfl = T.to_int8_tflite(model, Xtr)
    (out / "model_b_wetting_int8.tflite").write_bytes(tfl)
    pi = {s: T.tflite_predict_p1(tfl, win[s]["X"]) for s in ("val", "test")}
    vu = T.usable(win["val"])
    thr_i, met_i = T.choose_p_fast(pi["val"][vu], win["val"]["y"][vu])      # int8 gets its own val-chosen threshold
    report["int8"] = evaluate(pi, win, thr_i)
    report["int8"].update({"p_fast": thr_i, "fp_budget_met_on_val": met_i, "seed": T.SEEDS[0]})
    # concept section 5: int8 accepted only if wetting recall drops by <= 1 point vs float (same seed)
    d = {s: (report["float"]["seed0"][s]["model"]["wetting"]["recall"] or 0) - (report["int8"][s]["model"]["wetting"]["recall"] or 0)
         for s in ("val", "test")}
    report["int8_recall_drop_points"] = {s: 100 * v for s, v in d.items()}
    report["size"] = T.size_report(tfl)
    mean_int = ds["_meta"]["baseline_mean_interval_h"]
    report["model_a_baseline"] = {s: T.model_a_baseline_eval(ds[s], mean_int) for s in ("train", "val", "test")}
    report["model_a_baseline"]["trivial_median_mae_h"] = {s: T.trivial_median_mae(ds["train"], ds[s]) for s in ("val", "test")}
    (out / "model-b-wetting-v0.json").write_text(json.dumps(report, indent=1, default=float))
    (out / "model-b-wetting-v0.md").write_text(render_md(report, out / "rule-sweep.json"))
    (out / "size_report.json").write_text(json.dumps(report["size"], indent=1))
    print(json.dumps({k: report[k] for k in ("counts", "int8_recall_drop_points", "size")}, indent=1))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
