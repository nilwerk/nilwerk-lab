"""Writes LOCKED_INTERFACE.md: the interface values the enclosure assumes from the PCB (board outline, holes, cut-outs, light window,
AHT20 vents, pinhole, cell cavity, antenna overhang). Generated from params_v3 / board_facts, so it cannot drift from the model.
Run: python locked_interface.py. test_v3.py checks the committed file is current."""
import pathlib
import params_v3 as P
import board_facts as BF

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "LOCKED_INTERFACE.md"


def text():
    f = BF.facts()
    b = BF.boxes()
    sec = lambda r: P.H_SRC.get(r, ("ASSUMED", ""))[0]
    L = []
    a = L.append
    a("# Enclosure v3: locked interface values (for the PCB, 4.P2)")
    a("")
    a("Generated by `locked_interface.py` from `params_v3.py` and the board copy in `input/` (PR #73, 4.P2 slice 2). Do not edit by hand.")
    a("Frame (DXF): origin = board top-left corner, X right, Y up, mm. Board body y -42.0..0, tail below. Z = thickness: board bottom = 1.0 above the tray floor.")
    a("Status: **READ** = from the board file; **ASSUMED** = enclosure assumption (not in the board); **OPEN** = needs a decision (see the end).")
    a("")
    a("## 1. Board outline")
    a("| Value | Value (mm) | Status | Note |")
    a("|---|---|---|---|")
    a(f"| Body | {f['board_w']:.1f} x {f['body_l']:.1f} | READ | DXF OUTLINE |")
    a(f"| Tail (25 mm DXF) | {f['tail_w']:.1f} x {f['tail_l']:.1f} | READ | DXF OUTLINE; tip at y {f['tail_end']:.1f} |")
    a(f"| Thickness | {P.BOARD_T:.1f} | READ | KiCad general thickness (tolerance +-10 % per layout-brief) |")
    a(f"| Tail length variants | 14 mm: board tail {P.TAIL_L_VARIANT['14']:.1f}; 20 mm: board tail {P.TAIL_L_VARIANT['20']:.1f} | OPEN | electrode copper beyond the outer bottom face, A-071 (Arsany). Board change needed for both (DXF tail 25.0) |")
    a(f"| Electrode copper | 20 mm, y {-f['body_l'] - 1:.0f} to {f['copper_end']:.0f} | READ | E1 pad 1 (SOIL_PROBE), tip margin {P.TIP_MARGIN:.1f} to the tail end |")
    a(f"| Antenna module overhang | {f['overhang']:.1f} above the top edge, x {f['module_x0']:.1f}..{f['module_x1']:.1f} | READ | DXF MODULE_U1; enclosure keeps 1.0 air (ASSUMED) |")
    a("")
    a("## 2. Mounting")
    a("| Item | Value | Status | Note |")
    a("|---|---|---|---|")
    a("| Board mounting holes | **none on the board** | READ | the enclosure uses bosses and clamp pads; retention is an open point for Emil (item 6) |")
    a(f"| Screw bosses (enclosure) | 6 at (x, y) = {', '.join(f'({x:.1f}, {y:.1f})' for x, y in P.BOSS_XY)} | ASSUMED | M2 heat-set inserts, hole {P.INSERT_HOLE} x {P.INSERT_DEPTH} deep, boss d {P.BOSS_D} |")
    a(f"| Standoff pads under the board | 4 corners, height {P.STANDOFF} | ASSUMED | bottom copper is GND only |")
    a(f"| Clamp pads on the board top | free 2 x 2 mm squares (computed in `enclosure_v3.free_clamp_pads`) | OPEN | Emil asked for 2 more keep-clear pads or 2 M2 holes (item 6) |")
    a("")
    a("## 3. USB-C cut-out (J1)")
    a("| Item | Value | Status | Note |")
    a("|---|---|---|---|")
    a(f"| J1 centre (x = right edge, y) | x {P.BOARD_W:.2f}, y {P.J1_Y:.1f}, rotated 90 deg | READ | J1 footprint position |")
    a(f"| J1 height (board top to centre) | {P.H_BY_REF['J1']:.2f} (centre at z {P.J1_Z:.2f}) | {sec('J1')} | no datasheet read; see fit check |")
    a(f"| Window in right wall | {P.USB_W} x {P.USB_H} | ASSUMED | plug 8.94 x 3.26 + 0.3 per side |")
    a(f"| Overmold pocket (from outside) | {P.USB_POCKET[0]} x {P.USB_POCKET[1]} x {P.USB_POCKET[2]} deep | ASSUMED | wall left {P.WALL - P.USB_POCKET[2]:.1f} |")
    a("")
    a("## 4. Light window (U6, BH1750)")
    a("| Item | Value | Status | Note |")
    a("|---|---|---|---|")
    a(f"| U6 centre | ({P.U6[0]:.2f}, {P.U6[1]:.2f}) | READ | DXF footprint U6 (placeholder footprint, Emil to draw) |")
    a(f"| Window through the lid | d {P.WIN_D} | ASSUMED | clear film disc in a {P.WIN_CB_D} x {P.WIN_CB_DEPTH} counterbore |")
    a(f"| Collar under the lid | OD {P.COLLAR_OD}, tip {P.COLLAR_GAP} above the sensor top | ASSUMED | sensor top = board + U6 height {P.H_BY_REF['U6']} ({sec('U6')}) |")
    a("")
    a("## 5. AHT20 vents (U5)")
    a("| Item | Value | Status | Note |")
    a("|---|---|---|---|")
    xs = [P.U5[0] + (i - (P.VENT_N - 1) / 2) * P.VENT_PITCH for i in range(P.VENT_N)]
    a(f"| U5 centre | ({P.U5[0]:.2f}, {P.U5[1]:.2f}) | READ | DXF footprint U5 (placeholder footprint, Emil to draw from the AHT20 datasheet) |")
    a(f"| Slots | {P.VENT_N} x {P.VENT_W} x {P.VENT_L}, centres x = {', '.join(f'{x:.2f}' for x in xs)} | ASSUMED | pitch {P.VENT_PITCH} |")
    a(f"| Baffle cup | {P.CUP_W} x {P.CUP_L} x {P.CUP_DEPTH} deep, wall {P.CUP_WALL}, open toward the board interior (-Y) | ASSUMED | keeps the AHT20 out of the lid light path |")
    a("")
    a("## 6. Reset pinhole (SW3)")
    a("| Item | Value | Status | Note |")
    a("|---|---|---|---|")
    a(f"| SW3 centre | ({P.SW3[0]:.2f}, {P.SW3[1]:.2f}) | READ | DXF footprint SW3 (moved from 4.5 in #73) |")
    a(f"| Pin hole / guide tube | d {P.PIN_D} / OD {P.PIN_TUBE_OD}, ends {P.PIN_GAP} above the switch body | ASSUMED | switch height {P.H_BY_REF['SW3']} ({sec('SW3')}) |")
    a("")
    a("## 7. Cell bay (cell beside the board)")
    a("| Item | Value | Status | Note |")
    a("|---|---|---|---|")
    a(f"| Cavity (DXF) | x {P.CELL_X0:.1f}..{P.CELL_X1:.1f}, y {P.CELL_Y0:.1f}..{P.CELL_Y1:.1f}, {P.CELL_CAV[0]:.1f} x {P.CELL_CAV[1]:.1f} x {P.CELL_CAV[2]:.1f} deep | READ | gap to the board {P.CELL_GAP:.1f} |")
    a("| Cell | EEMB LP603449-PCM, 51 x 34.5 x 6.3 (listing) | READ (bay) | Arsany to confirm the cell (A-034) |")
    a("")
    a("## 8. Housing envelope (for Emil's keep-out)")
    a("| Item | Value | Status | Note |")
    a("|---|---|---|---|")
    a(f"| Inner cavity | {P.INNER_X1 - P.INNER_X0:.1f} x {P.INNER_Y1 - P.INNER_Y0:.1f} x {P.INNER_H:.1f} | ASSUMED | J2 height is the open point (4.5 ASSUMED vs 5.5 distributor) |")
    a(f"| Outer, lid on | {P.OUT_X1 - P.OUT_X0:.1f} x {P.OUT_Y1 - P.OUT_Y0:.1f} x {P.FLOOR + P.INNER_H + P.LID_T:.1f} | ASSUMED | floor {P.FLOOR} + inner + lid {P.LID_T}; +1.0 gasket (not modelled) |")
    a("")
    a("## 9. Open points (NEEDS ARSANY / Emil)")
    a(f"1. **Tail length (A-071)**: choose 14 or 20 mm. Board tail becomes {P.TAIL_L_VARIANT['14']:.1f} or {P.TAIL_L_VARIANT['20']:.1f} mm; the DXF is 25.0 today.")
    a(f"2. **J2 height**: model 4.5 ASSUMED; distributor values 5.5 mm. At 5.5 the inner height must grow by 1.0 mm.")
    a("3. **Board retention**: two more keep-clear pads or two M2 holes (no metal within 15 mm of the antenna).")
    a("4. **Device heights** still ASSUMED (see `params_v3.H_SRC`): J1, U3 and the 0603/SOT parts.")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    OUT.write_text(text(), encoding="utf-8")
    print("wrote", OUT)
